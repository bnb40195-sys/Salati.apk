package com.example.ui.screens

import androidx.compose.material3.ExperimentalMaterial3Api
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import com.example.data.models.*
import com.example.data.services.CalculationMethod
import com.example.data.services.JuristicMethod
import com.example.data.services.WeatherInfo

/**
 * AdvancedSettingsScreen now delegates directly to the unified SettingsScreen
 * ensuring complete consolidation of general and advanced settings in one place.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AdvancedSettingsScreen(
    selectedCity: CityLocation,
    calculationMethod: CalculationMethod,
    juristicMethod: JuristicMethod,
    fridayFirstAdhan: Boolean,
    fridaySecondAdhan: Boolean,
    fridaySoundOnly: Boolean,
    salawatIntervalMinutes: Int,
    prePrayerBigMessage: Boolean,
    prePrayerMinutesBefore: Int,
    hijriType: String,
    hijriAdjustment: Int,
    monthDisplayMode: String,
    utcMode: String,
    manualUtcHours: Double,
    currentBgTheme: String,
    sections: List<AppSectionModel> = emptyList(),
    wallpapers: List<WallpaperModel> = emptyList(),
    adhanAudios: List<AdhanAudioModel> = emptyList(),
    tawbahStories: List<TawbahStory> = emptyList(),
    prophetStories: List<ProphetStory> = emptyList(),
    islamicQAs: List<IslamicQA> = emptyList(),
    onSaveCityCoords: (Double, Double, String) -> Unit,
    onSelectCalculationMethod: (CalculationMethod) -> Unit,
    onSelectJuristicMethod: (JuristicMethod) -> Unit,
    onUpdateFridaySettings: (Boolean, Boolean, Boolean) -> Unit,
    onUpdateSalawatInterval: (Int) -> Unit,
    onUpdatePrePrayerSettings: (Boolean, Int) -> Unit,
    onUpdateHijriSettings: (String, Int, String) -> Unit,
    onUpdateUtcSettings: (String, Double) -> Unit,
    onSelectBgTheme: (String) -> Unit,
    onOpenCreatorStudio: () -> Unit,
    onOpenWidgetsStudio: () -> Unit,
    onToggleSection: (String, Boolean) -> Unit = { _, _ -> },
    onDeleteSection: (String) -> Unit = {},
    onAddSection: (String, String) -> Unit = { _, _ -> },
    onResetSections: () -> Unit = {},
    onAddWallpaper: (String, String, Long, String?) -> Unit = { _, _, _, _ -> },
    onDeleteWallpaper: (String) -> Unit = {},
    onResetWallpapers: () -> Unit = {},
    onAddSound: (String, String, String, String) -> Unit = { _, _, _, _ -> },
    onDeleteSound: (String) -> Unit = {},
    onResetSounds: () -> Unit = {},
    onAddTawbahStory: (String, String, String, String, String) -> Unit = { _, _, _, _, _ -> },
    onDeleteTawbahStory: (String) -> Unit = {},
    onResetTawbahStories: () -> Unit = {},
    onAddProphetStory: (String, String, String, String, String, String) -> Unit = { _, _, _, _, _, _ -> },
    onDeleteProphetStory: (String) -> Unit = {},
    onResetProphetStories: () -> Unit = {},
    onAddQA: (String, String, String, String) -> Unit = { _, _, _, _ -> },
    onDeleteQA: (String) -> Unit = {},
    onResetQAs: () -> Unit = {},
    onPlayTestAudio: (String, String) -> Unit = { _, _ -> },
    onOpenPrayerAdjustments: () -> Unit = {},
    onOpenAthkarDuas: (String) -> Unit = {},
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    SettingsScreen(
        selectedCity = selectedCity,
        calculationMethod = calculationMethod,
        juristicMethod = juristicMethod,
        prayerOffsets = emptyMap(),
        weatherInfo = WeatherInfo(),
        isDarkMode = false,
        fridayFirstAdhan = fridayFirstAdhan,
        fridaySecondAdhan = fridaySecondAdhan,
        fridaySoundOnly = fridaySoundOnly,
        salawatIntervalMinutes = salawatIntervalMinutes,
        prePrayerBigMessage = prePrayerBigMessage,
        prePrayerMinutesBefore = prePrayerMinutesBefore,
        hijriType = hijriType,
        hijriAdjustment = hijriAdjustment,
        monthDisplayMode = monthDisplayMode,
        utcMode = utcMode,
        manualUtcHours = manualUtcHours,
        currentBgTheme = currentBgTheme,
        sections = sections,
        wallpapers = wallpapers,
        adhanAudios = adhanAudios,
        tawbahStories = tawbahStories,
        prophetStories = prophetStories,
        islamicQAs = islamicQAs,
        initialTab = 1,
        onSaveCityCoords = onSaveCityCoords,
        onSelectCalculationMethod = onSelectCalculationMethod,
        onSelectJuristicMethod = onSelectJuristicMethod,
        onUpdateFridaySettings = onUpdateFridaySettings,
        onUpdateSalawatInterval = onUpdateSalawatInterval,
        onUpdatePrePrayerSettings = onUpdatePrePrayerSettings,
        onUpdateHijriSettings = onUpdateHijriSettings,
        onUpdateUtcSettings = onUpdateUtcSettings,
        onSelectBgTheme = onSelectBgTheme,
        onOpenCreatorStudio = onOpenCreatorStudio,
        onOpenWidgetsStudio = onOpenWidgetsStudio,
        onToggleSection = onToggleSection,
        onDeleteSection = onDeleteSection,
        onAddSection = onAddSection,
        onResetSections = onResetSections,
        onAddWallpaper = onAddWallpaper,
        onDeleteWallpaper = onDeleteWallpaper,
        onResetWallpapers = onResetWallpapers,
        onAddSound = onAddSound,
        onDeleteSound = onDeleteSound,
        onResetSounds = onResetSounds,
        onAddTawbahStory = onAddTawbahStory,
        onDeleteTawbahStory = onDeleteTawbahStory,
        onResetTawbahStories = onResetTawbahStories,
        onAddProphetStory = onAddProphetStory,
        onDeleteProphetStory = onDeleteProphetStory,
        onResetProphetStories = onResetProphetStories,
        onAddQA = onAddQA,
        onDeleteQA = onDeleteQA,
        onResetQAs = onResetQAs,
        onPlayTestAudio = onPlayTestAudio,
        onOpenPrayerAdjustments = onOpenPrayerAdjustments,
        onOpenAthkarDuas = onOpenAthkarDuas,
        onBack = onBack,
        modifier = modifier
    )
}
